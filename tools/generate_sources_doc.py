#!/usr/bin/env python3
"""
Generate docs/SOURCES.md from the citation register.

The document is derived, never hand-edited, so it cannot drift from the
code the test suite checks. CI regenerates it and diffs the result against
what is committed; a mismatch fails the build.

    python tools/generate_sources_doc.py > docs/SOURCES.md
"""
from __future__ import annotations
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from numeral_systems import sources  # noqa: E402


def emit(line: str = "") -> None:
    sys.stdout.write(line + "\n")


def main() -> None:
    emit("# Sources")
    emit()
    emit("> Generated by `tools/generate_sources_doc.py` from")
    emit("> `numeral_systems/sources.py`. Do not edit by hand -- edit the")
    emit("> register and regenerate. CI diffs this file against a fresh")
    emit("> generation, so the two cannot drift apart.")
    emit()
    emit("Every historical claim this library makes is listed below with the")
    emit("citations supporting it. `tests/test_sources.py` fails the build if")
    emit("a claim has no citation, if a citation names a claim nobody makes,")
    emit("or if a claim rests on a popular-tier source alone.")
    emit()

    emit("## How to read the two labels")
    emit()
    emit("Each citation carries a **tier** (what kind of source it is) and a")
    emit("**verification** level (how far this release actually checked it).")
    emit()
    emit("| verification | meaning |")
    emit("|---|---|")
    emit("| `consulted` | the source text was read directly for this release |")
    emit("| `bibliographic` | details confirmed and the source is the recognised authority, but its pages were **not** read for this release |")
    emit("| `reported` | known here only through secondary summaries |")
    emit()
    emit("Most entries are `bibliographic`. That is stated rather than")
    emit("implied: a citation can be correct and still be a claim about one's")
    emit("own diligence. The open reading list is published below.")
    emit()

    emit("## Claims")
    emit()
    for claim, wording in sorted(sources.CLAIMS.items()):
        emit(f"### `{claim}`")
        emit()
        emit(wording)
        emit()
        for src in sources.sources_for(claim):
            emit(
                f"- **[{src['key']}]** ({src['tier']}; {src['verification']}) "
                f"{src['text']}"
            )
        if claim in sources.EXECUTION_CHECKED:
            emit()
            emit(f"**Also checked by execution.** {sources.EXECUTION_CHECKED[claim]}")
        emit()

    emit("## Open reading list")
    emit()
    emit("These claims rest on recognised authorities whose pages were not")
    emit("read while preparing this release. Reading them is the next step in")
    emit("strengthening this library's evidence, and the list is published")
    emit("rather than hidden.")
    emit()
    emit("```text")
    emit(sources.reading_list())
    emit("```")
    emit()

    emit("## Full register")
    emit()
    emit("```text")
    emit(sources.bibliography())
    emit("```")


if __name__ == "__main__":
    main()
